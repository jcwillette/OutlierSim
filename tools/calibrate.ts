/**
 * Compare simulated bot matches with real matches from The Blue Alliance.
 *
 * OPT-IN ONLY (ADR 0004): games are built blind from the manual. Run this only when the owner asks.
 *
 *   npm run calibrate -- --game <id> [--events 2024casj,2024txhou] [--matches 200] [--difficulty normal]
 *                        [--lineups blueId,redId]  (default: random robots, like the menu's random preset)
 *                        [--write]   refresh the generated table in src/games/<id>/CALIBRATION.md
 *                        [--dump]    print one real score_breakdown (to write metrics)
 *
 * Real: the spec's `events`, or every official event of its `season`, qualification matches.
 * Sim: bot-vs-bot matches with breakdowns on; each alliance-match is one sample on either side.
 *
 * TBA: www.thebluealliance.com is proxy-authenticated in the cloud environment. Elsewhere set
 * TBA_KEY. Responses are cached in work/tba-cache/.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Difficulty } from '../src/engine/ai/bot.ts';
import { DEFAULT_METRICS, stats, type CalibrationSpec, type Stats } from '../src/engine/sim/calibration.ts';
import { GAMES } from '../src/games/index.ts';
import { runSims } from './sim.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name: string, fallback?: string) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : fallback;
};
const flag = (name: string) => process.argv.includes(`--${name}`);

interface TbaMatch {
  key: string;
  comp_level: string;
  alliances: Record<'red' | 'blue', { score: number }>;
  score_breakdown: Record<'red' | 'blue', Record<string, unknown>> | null;
}

async function tba<T>(path: string): Promise<T> {
  const cacheDir = join(root, 'work', 'tba-cache');
  const cache = join(cacheDir, path.replace(/[^a-z0-9]+/gi, '_') + '.json');
  if (existsSync(cache)) return JSON.parse(readFileSync(cache, 'utf8')) as T;
  const headers: Record<string, string> = { accept: 'application/json' };
  if (process.env.TBA_KEY) headers['X-TBA-Auth-Key'] = process.env.TBA_KEY;
  const res = await fetch(`https://www.thebluealliance.com/api/v3${path}`, { headers });
  if (!res.ok) throw new Error(`TBA ${path}: HTTP ${res.status}`);
  const data = (await res.json()) as T;
  mkdirSync(cacheDir, { recursive: true });
  writeFileSync(cache, JSON.stringify(data));
  return data;
}

const fmt = (s: Stats) =>
  Number.isNaN(s.mean)
    ? 'n/a'
    : s.mean < 1 && s.sd <= 0.6
      ? s.mean.toFixed(2)
      : `${s.mean.toFixed(1)} ± ${s.sd.toFixed(1)}`;

interface TbaEvent {
  key: string;
  event_type: number;
}

/** Official events of a season: regionals, districts, district championships (and divisions), Championship. */
async function seasonEvents(year: number): Promise<string[]> {
  const all = await tba<TbaEvent[]>(`/events/${year}`);
  return all.filter((e) => e.event_type >= 0 && e.event_type <= 5).map((e) => e.key);
}

const MARK_START = '<!-- calibrate:start (generated by npm run calibrate -- --write) -->';
const MARK_END = '<!-- calibrate:end -->';

async function main() {
  const gameId = arg('game');
  const entry = GAMES.find((g) => g.definition.id === gameId);
  if (!entry) throw new Error(`--game must be one of: ${GAMES.map((g) => g.definition.id).join(', ')}`);
  const spec: CalibrationSpec = entry.calibration ?? { events: [], metrics: DEFAULT_METRICS };
  const events =
    arg('events')?.split(',') ?? (spec.season !== undefined ? await seasonEvents(spec.season) : spec.events);
  if (!events.length) throw new Error('No events: pass --events or add calibration.ts with events');
  const levels = spec.compLevels ?? ['qm'];

  const real: TbaMatch[] = [];
  for (const e of events) {
    const ms = await tba<TbaMatch[]>(`/event/${e}/matches`);
    real.push(
      ...ms.filter((m) => levels.includes(m.comp_level) && m.score_breakdown && m.alliances.red.score >= 0),
    );
  }
  if (flag('dump')) {
    console.log(JSON.stringify(real[0]?.score_breakdown?.blue, null, 2));
    return;
  }
  const difficulty = (arg('difficulty', 'normal') as Difficulty) ?? 'normal';
  const n = Number(arg('matches', '200'));
  const lineups = arg('lineups')?.split(',') as [string, string] | undefined;
  const { results } = await runSims(entry.definition.id, n, {
    difficulty,
    ...(lineups ? { lineups } : { random: true }),
  });
  const robots = lineups
    ? `the ${lineups.join(' vs ')} lineups`
    : 'random robot types (the menu’s random preset)';

  const rows = spec.metrics.map((m) => {
    const r: number[] = [];
    for (const match of real) {
      for (const side of ['red', 'blue'] as const) {
        const v = m.real(match.score_breakdown![side], match.alliances[side].score);
        if (v !== null && Number.isFinite(v)) r.push(v);
      }
    }
    const s = results.flatMap((res) => [m.sim(res.blue), m.sim(res.red)]);
    return { name: m.name, real: stats(r), sim: stats(s) };
  });

  const lines = [
    `| Metric (per alliance per match) | Real mean ± sd | Real p50 / p90 | Sim mean ± sd | Sim p50 / p90 | Sim ÷ real |`,
    `| --- | --- | --- | --- | --- | --- |`,
    ...rows.map(
      (r) =>
        `| ${r.name} | ${fmt(r.real)} | ${r.real.p50.toFixed(0)} / ${r.real.p90.toFixed(0)} | ${fmt(r.sim)} | ${r.sim.p50.toFixed(0)} / ${r.sim.p90.toFixed(0)} | ${(r.sim.mean / r.real.mean).toFixed(2)} |`,
    ),
  ];
  const table = lines.join('\n');
  const from = events.length > 6 ? `${events.length} events` : events.join(', ');
  console.log(
    `Real: ${real.length} matches from ${from} (${levels.join(', ')}). Sim: ${n} matches, ${difficulty} bots, ${robots}.\n`,
  );
  console.log(table);

  if (flag('write')) {
    const file = join(root, 'src', 'games', entry.definition.id, 'CALIBRATION.md');
    const where =
      spec.season !== undefined && !arg('events')
        ? `every official ${spec.season} event (${events.length})`
        : events.map((e) => `\`${e}\``).join(', ');
    const generated = [
      MARK_START,
      '',
      `\`npm run calibrate -- --game ${entry.definition.id}${arg('matches') ? ` --matches ${n}` : ''}${lineups ? ` --lineups ${lineups.join(',')}` : ''} --difficulty ${difficulty} --write\`, ${new Date().toISOString().slice(0, 10)}:`,
      '',
      `- Real: ${real.length} matches (${levels.join(', ')}) from ${where}, via The Blue Alliance.`,
      `- Sim: ${n} bot-vs-bot matches, all six robots \`${difficulty}\`, breakdowns on, ${robots}.`,
      '- Means per alliance per match. A ratio near 1.0 means the sim plays like those events.',
      '',
      table,
      '',
      MARK_END,
    ].join('\n');
    const old = existsSync(file) ? readFileSync(file, 'utf8') : '';
    const i = old.indexOf(MARK_START);
    const j = old.indexOf(MARK_END);
    const md =
      i >= 0 && j > i
        ? old.slice(0, i) + generated + old.slice(j + MARK_END.length)
        : [
            `# Calibration: ${entry.definition.name}`,
            '',
            generated,
            '',
            '## Interpretation and tuning notes',
            '',
            spec.notes ??
              '_Explain big gaps here and what was tuned (archetype speeds, cycle times, accuracy)._',
            '',
          ].join('\n');
    writeFileSync(file, md);
    console.log(`\nWrote ${file}`);
  }
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
